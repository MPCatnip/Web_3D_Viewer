/* Generate vendor/three-bundle.min.js — the single vendor payload build.mjs inlines.
   It contains:
     1. a TREE-SHAKEN three core (npm `three`, pinned in package.json to the same
        r137 line as the old vendor/three.min.js), bundled down to only the THREE
        members that src/app.js and the vendor example files actually use, and
        exposed as the global `THREE`;
     2. minified copies of the CHECKED-IN example files (controls / loaders /
        CSS2D) — kept as the source of truth rather than npm three/examples, so
        runtime behaviour is byte-for-byte what shipped before — which attach
        their classes onto that global.
   Also writes tools/three-members.json so a dependency-free `node build.mjs` can
   verify the bundle still covers every THREE.* member app.js uses.

   One-time setup: npm install        Regenerate: npm run vendor
   Re-run whenever src/app.js starts using a new THREE.* member or a vendor
   example file changes (build.mjs errors if the member list goes stale). */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";
import * as THREE_NS from "three";

const repo = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => fs.readFileSync(path.join(repo, p), "utf8");

const EXAMPLE_FILES = [
  "vendor/OrbitControls.js",
  "vendor/TransformControls.js",
  "vendor/OBJLoader.js",
  "vendor/STLLoader.js",
  "vendor/GLTFLoader.js",
  "vendor/CSS2DRenderer.js",
  // fat lines (edge overlay): geometry + material must precede LineSegments2
  "vendor/LineSegmentsGeometry.js",
  "vendor/LineMaterial.js",
  "vendor/LineSegments2.js",
];

// members read via computed / `"x" in THREE` checks that the THREE.<name> scan can't see
const FORCE_INCLUDE = ["sRGBEncoding", "REVISION"];

/* every THREE.<member> read in a source (also catches `"name" in THREE` probes) */
function scanMembers(code) {
  const out = new Set();
  for (const m of code.matchAll(/\bTHREE\.([A-Za-z_$][A-Za-z0-9_$]*)/g)) out.add(m[1]);
  for (const m of code.matchAll(/["']([A-Za-z_$][A-Za-z0-9_$]*)["']\s+in\s+THREE\b/g)) out.add(m[1]);
  return out;
}
/* names an example file attaches to THREE itself (THREE.OBJLoader = OBJLoader) */
function scanAttached(code) {
  const out = new Set();
  for (const m of code.matchAll(/\bTHREE\.([A-Za-z_$][A-Za-z0-9_$]*)\s*=[^=]/g)) out.add(m[1]);
  return out;
}

const exampleSrc = EXAMPLE_FILES.map((f) => ({ f, code: read(f) }));
const used = new Set(FORCE_INCLUDE);
scanMembers(read("src/app.js")).forEach((n) => used.add(n));
const attached = new Set();
exampleSrc.forEach(({ code }) => {
  scanMembers(code).forEach((n) => used.add(n));
  scanAttached(code).forEach((n) => attached.add(n));
});

const exportsSet = new Set(Object.keys(THREE_NS));
const members = [...used].filter((n) => exportsSet.has(n)).sort();
const unknown = [...used].filter((n) => !exportsSet.has(n) && !attached.has(n)).sort();
if (unknown.length) {
  throw new Error(
    "THREE members used but neither exported by three nor attached by a vendor example file:\n  " +
    unknown.join(", ") +
    "\n(typo, a comment-only mention worth ignoring here, or the pinned three version is too old)"
  );
}

const threeVersion = JSON.parse(read("node_modules/three/package.json")).version;
const entry =
  `import { ${members.join(", ")} } from "three";\n` +
  `globalThis.THREE = { ${members.join(", ")} };\n`;

const core = await esbuild.build({
  stdin: { contents: entry, resolveDir: repo, loader: "js" },
  bundle: true, minify: true, format: "iife", target: "es2018", charset: "utf8",
  legalComments: "none", write: false,
});

let out =
  "/* three-bundle.min.js — GENERATED by tools/build_vendor.mjs (npm run vendor). DO NOT EDIT.\n" +
  `   three@${threeVersion} core, tree-shaken to the ${members.length} THREE members used by src/app.js and the\n` +
  "   vendor example files, exposed as the global THREE; the example files appended\n" +
  "   below (minified verbatim from vendor/*.js) attach their classes onto it. */\n" +
  core.outputFiles[0].text;

for (const { f, code } of exampleSrc) {
  const min = await esbuild.transform(code, { minify: true, target: "es2018", charset: "utf8", legalComments: "none" });
  out += `/* ---- ${f} ---- */\n` + min.code;
}

fs.writeFileSync(path.join(repo, "vendor/three-bundle.min.js"), out);
fs.writeFileSync(
  path.join(repo, "tools/three-members.json"),
  JSON.stringify({ three: threeVersion, members, attached: [...attached].sort() }, null, 2) + "\n"
);

const kb = (n) => (n / 1024).toFixed(0) + " KB";
const before = EXAMPLE_FILES.concat("vendor/three.min.js")
  .reduce((s, f) => s + fs.statSync(path.join(repo, f)).size, 0);
console.log(`Wrote vendor/three-bundle.min.js (${kb(out.length)}; replaces ${kb(before)} of vendor files)`);
console.log(`Wrote tools/three-members.json (${members.length} core members, ${attached.size} example-attached)`);
